func surfaceCatalog(t *testing.T) fs.FS {
	t.Helper()
	combined, err := folio.WithPresetPacks(folio.BundledPresets, scaffolding.Presets)
	if err != nil {
		t.Fatal(err)
	}
	return combined
}
func TestPresetsPreservePreSplitBytes(t *testing.T) {
	data, err := os.ReadFile("testdata/pre-split-file-digests.json")
	if err != nil {
		t.Fatal(err)
	}
	var before map[string][]service.FileResult
	if decodeErr := json.Unmarshal(data, &before); decodeErr != nil {
		t.Fatal(decodeErr)
	}
	for _, id := range []string{"surface-app", "surface-desk"} {
		dir := t.TempDir()
		svc := service.New(service.Options{BundledFS: surfaceCatalog(t), UserDir: filepath.Join(dir, "user"), FolioVersion: folio.Version, Now: time.Date(2026, 11, 18, 0, 0, 0, 0, time.UTC)})
		after, renderErr := svc.New(service.NewOptions{PresetID: id, TargetDir: filepath.Join(dir, "app"), Inputs: map[string]any{"repo_name": "pack-check"}})
		if renderErr != nil {
			t.Fatal(renderErr)
		}
		if !reflect.DeepEqual(before[id], after.Files) {
			t.Fatalf("%s generated bytes/provenance changed during relocation", id)
		}
	}
}
func TestSharedAgentDependencyIsRequiredAndVersioned(t *testing.T) {
	opts := service.NewOptions{PresetID: "surface-desk", TargetDir: "example", Inputs: map[string]any{"repo_name": "dependency-check"}}
	svc := service.New(service.Options{BundledFS: scaffolding.Presets, UserDir: t.TempDir()})
	if _, err := svc.Plan(opts); err == nil || !strings.Contains(err.Error(), "agent-dir") {
		t.Fatalf("expected missing agent-dir, got %v", err)
	}
	generic := fstest.MapFS{}
	err := fs.WalkDir(folio.BundledPresets, ".", func(name string, e fs.DirEntry, walkErr error) error {
		if walkErr != nil || e.IsDir() {
			return walkErr
		}
		data, readErr := fs.ReadFile(folio.BundledPresets, name)
		if readErr != nil {
			return readErr
		}
		generic[name] = &fstest.MapFile{Data: data}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	agent := generic["presets/agent-dir/preset.yaml"]
	original := string(agent.Data)
	changed := strings.Replace(original, "version: 0.1.0", "version: 9.0.0", 1)
	if changed == original {
		t.Fatal("version mutation did not apply")
	}
	agent.Data = []byte(changed)
	combined, packErr := folio.WithPresetPacks(generic, scaffolding.Presets)
	if packErr != nil {
		t.Fatal(packErr)
	}
	svc = service.New(service.Options{BundledFS: combined, UserDir: t.TempDir()})
	if _, versionErr := svc.Plan(opts); versionErr == nil || !strings.Contains(versionErr.Error(), "does not satisfy constraint") {
		t.Fatalf("expected version constraint error, got %v", versionErr)
	}
}
